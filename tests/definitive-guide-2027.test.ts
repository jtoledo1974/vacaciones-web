import {test} from 'node:test';
import assert from 'node:assert/strict';
import {evaluate2027Final,canComplete2027,evaluate2027Candidate,type PolicyState} from '../domain/policy-2027.ts';

/** Independent histogram fixtures: each occupant has a distinct, complete right. */
function allocation(pre:number[],summer:number[],post:number[]):PolicyState {
 const state:PolicyState={cycles:[],members:[],awards:[]};
 [pre,summer,post].forEach((counts,period)=>counts.forEach((count,index)=>{
  const date=`2027-${['01','06','10'][period]}-${String(index+1).padStart(2,'0')}`;
  state.cycles.push({date,period:period as 0|1|2});
  for(let i=0;i<count;i++){
   const id=`p${state.members.length}`;state.members.push({id,entitlement:1});
   state.awards.push({member_id:id,cycle_date:date});
  }
 }));
 return state;
}

test('guide: summer permits one-person cycles generated by EC3 and EC4',()=>{
 for(const summer of [[1,3,2],[1,4,2],[1,1,3,3],[1,1,4,2]]){
  const state=allocation([2],summer,[2]);
  assert.equal(evaluate2027Final(state).valid,true,JSON.stringify(summer));
  assert.equal(canComplete2027(state).status,'possible');
  assert.equal(evaluate2027Candidate(state,[]).allowed,true);
 }
});
test('guide: summer has two shared EC3/EC4 permits, with no compulsory singles',()=>{
 assert.equal(evaluate2027Final(allocation([2],[2,4,2,4],[2])).valid,true);
 assert.equal(evaluate2027Final(allocation([2],[1,1,1,3,3,3],[2])).valid,false);
 // Three singles cannot be justified by two extras even with a fourth destination.
 assert.equal(evaluate2027Final(allocation([2],[1,1,1,4,3],[2])).valid,false);
});
test('guide: PRE and POST cannot borrow each other’s source holes',()=>{
 assert.equal(evaluate2027Final(allocation([4,3],[2],[1,3])).valid,false);
 assert.equal(evaluate2027Final(allocation([4,2],[2],[2])).valid,true);
 assert.equal(evaluate2027Final(allocation([2],[2],[4,1])).valid,true);
});
test('guide: PRE EC4 may leave the third single; a fourth single exceeds three permits',()=>{
 assert.equal(evaluate2027Final(allocation([4,1],[2],[2])).valid,true);
 assert.equal(evaluate2027Final(allocation([1,1,1,3,3,4],[2],[2])).valid,true);
 assert.equal(evaluate2027Final(allocation([1,1,4],[2],[2])).valid,true,'EC3 and EC4 chained');
 assert.equal(evaluate2027Final(allocation([1,1,1,1,3,3,4,3],[2],[2])).valid,false);
});
test('guide: no empty cycle, exclusions still apply',()=>{
 assert.equal(evaluate2027Final(allocation([2],[0,4],[2])).valid,false);
 const state=allocation([2],[1,4,2],[2]);state.cycles.find(c=>c.date==='2027-06-02')!.fourthExcluded=true;
 assert.equal(evaluate2027Final(state).valid,false);
});
test('guide: partial summer completion recovers a last legal award and its witness',()=>{
 const final=allocation([2],[1,3,2],[2]);
 const last=final.awards.pop()!;
 assert.equal(canComplete2027(final,{maxChecks:10000}).status,'possible');
 assert.equal(evaluate2027Candidate(final,[last]).allowed,true);
});

test('guide: exhaustive four-cycle summer oracle with at most two EC3/EC4 moves',()=>{
 // Independent forward model: ordinary cycles start at 2/3; a permit moves
 // one place locally to a destination at 2 (EC3) or 3 (EC4). No empty source.
 const reachable=new Set<string>();
 function visit(counts:number[],remaining:number):void {
  reachable.add(counts.join(','));if(!remaining)return;
  counts.forEach((source,i)=>counts.forEach((target,j)=>{
   if(i===j||source<2||target<2||target>3)return;
   const next=[...counts];next[i]--;next[j]++;visit(next,remaining-1);
  }));
 }
 for(let bits=0;bits<16;bits++)visit(Array.from({length:4},(_,i)=>2+((bits>>i)&1)),2);
 for(let bits=0;bits<256;bits++){
  const counts=Array.from({length:4},(_,i)=>1+((bits>>(2*i))&3));
  assert.equal(evaluate2027Final(allocation([2],counts,[2])).valid,reachable.has(counts.join(',')),counts.join(','));
 }
});
